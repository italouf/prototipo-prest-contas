import { expect, test } from '@playwright/test';

test('biblioteca: grandes listas, filtros, retorno e relatórios completos', async ({ page }, info) => {
  test.setTimeout(120_000);
  await page.goto('/accounts/login/');
  await page.getByLabel('Usuário').fill('overview-e2e');
  await page.getByLabel('Senha', { exact: true }).fill('overview-test-123');
  await page.getByRole('button', { name: /entrar/i }).click();
  await page.goto('/materiais/?acompanhamento=1');
  const lista = page.getByTestId('lista-materiais');
  await expect(page.locator('.materials-result-heading')).toContainText('240 materiais');
  await expect(lista.locator('tbody tr')).toHaveCount(25);
  await page.getByRole('link', { name: 'Próxima', exact: true }).click();
  await expect(page).toHaveURL(/page=2/);
  const antes = page.url();
  await lista.getByRole('link', { name: 'Editar', exact: true }).first().click();
  await page.getByLabel(/^Título/).fill('Artigo PDI revisado na consulta');
  await page.getByRole('button', { name: 'Salvar', exact: true }).click();
  await expect(page).toHaveURL(antes);
  await expect(lista).toContainText('Artigo PDI revisado na consulta');
  await page.getByLabel('Pilar', { exact: true }).selectOption('AT');
  await page.getByRole('button', { name: 'Aplicar filtros' }).click();
  await expect(page.locator('.materials-result-heading')).toContainText('120 materiais');
  expect(new URL(page.url()).searchParams.has('page')).toBe(false);
  await page.getByLabel('Por página').selectOption('10');
  await page.getByRole('button', { name: 'Aplicar filtros' }).click();
  await expect(lista.locator('tbody tr')).toHaveCount(10);
  const consulta = page.url();
  await lista.locator('tbody tr').first().locator('td').nth(1).getByRole('link').click();
  await expect(page.getByRole('heading', { name: 'White paper', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Voltar à consulta anterior' }).click();
  await expect(page).toHaveURL(consulta);
  const csv = await page.request.get((await page.getByRole('link', { name: 'Baixar resultados (CSV)' }).getAttribute('href'))!);
  expect((await csv.text()).trim().split(/\r?\n/)).toHaveLength(121);
  const href = (await page.getByRole('link', { name: 'Relatório completo', exact: true }).getAttribute('href'))!;
  const relatorio = await page.context().newPage();
  await relatorio.goto(href);
  await expect(relatorio.getByTestId('lista-materiais').locator('tbody tr')).toHaveCount(120);
  await expect(relatorio.getByRole('link', { name: 'Editar', exact: true })).toHaveCount(0);
  const pdf = await relatorio.pdf({ path: info.outputPath('relatorio-completo.pdf'), landscape: true });
  expect(pdf.subarray(0, 4).toString()).toBe('%PDF');
  await page.screenshot({ path: info.outputPath('biblioteca-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('biblioteca-mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/pilar/4/?base=fis&acompanhamento=1&entregaveis_at=1');
  const quadro = page.getByTestId('entregaveis-at-accordion');
  await expect(quadro).toContainText('120 materiais');
  await expect(quadro).not.toContainText('Relatório AT 119');
  await expect(quadro.locator('tbody tr')).toHaveCount(9);
  await page.screenshot({ path: info.outputPath('dashboard-compacto.png'), fullPage: true });
});
