TABS_BY_SLUG: Dict[str, TabFormSpec] = {t.slug: t for t in TAB_FORM_SPECS}


def tabs_for_pilar(pilar_codigo: str) -> List[TabFormSpec]:
    return [t for t in TAB_FORM_SPECS if t.pilar_codigo == pilar_codigo]


def get_tab_spec(pilar_codigo: str, slug: Optional[str] = None) -> TabFormSpec:
    pilar_tabs = tabs_for_pilar(pilar_codigo)
    if slug and slug in TABS_BY_SLUG and TABS_BY_SLUG[slug].pilar_codigo == pilar_codigo:
        return TABS_BY_SLUG[slug]
    return pilar_tabs[0]


def get_domain_choices(categoria: str, required: bool = True) -> List[Tuple[str, str]]:
    vals = list(
        ListaDominioEmbrapii.objects.filter(categoria=categoria, ativo=True)
        .order_by("ordem", "valor")
        .values_list("valor", flat=True)
    )
    choices = [(v, v) for v in vals]
    if not required:
        return [("", "---------")] + choices
    return [("", "Selecione...")] + choices


def get_project_code_suggestions(ciclo, spec: TabFormSpec) -> List[str]:
    if not spec.project_source_model:
        return []
    qs = spec.project_source_model.objects.filter(competencia_mensal__ciclo=ciclo).order_by(
        "data_inicio", "id"
    )
    seen_dates: Dict[object, int] = {}
    codigos = []
    abrev = ciclo.abreviacao_cc or "QIN"
    for proj in qs:
        d = getattr(proj, "data_inicio", None)
        if not d:
            continue
        seq = seen_dates.get(d, 0) + 1
        seen_dates[d] = seq
        codigos.append(proj.codigo_preview(seq=seq, abrev=abrev))
    return codigos
